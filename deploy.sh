        # proxy_buffer_size.
        proxy_buffer_size 64k;
        proxy_buffers 8 64k;
        proxy_busy_buffers_size 128k;
    }

    # Health endpoint — kept out of the access log.
    location = /up {
        access_log off;
        proxy_pass http://127.0.0.1:8081;
        proxy_set_header Host $host;
        proxy_set_header X-Forwarded-Proto $scheme;
    }

    location ~ /\.(?!well-known) {
        deny all;
    }
}
NGINX_EOF
