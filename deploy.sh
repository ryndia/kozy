# Reverse proxy for kozy.ryndia.space → the app container on 127.0.0.1:8081

# Connection: upgrade must only be sent for actual WebSocket upgrades. Sending
# it unconditionally gives every ordinary request a bogus hop-by-hop header.
# The variable is namespaced because other vhosts on this host may define
# their own $connection_upgrade map at http level.
map $http_upgrade $kozy_connection_upgrade {
    default upgrade;
    ''      close;
}

server {
    listen 80;
    listen [::]:80;
    server_name kozy.ryndia.space;

    location /.well-known/acme-challenge/ {
        root /var/www/certbot;
    }

    location / {
        return 301 https://$server_name$request_uri;
    }
}

server {
    listen 443 ssl;
    listen [::]:443 ssl;
    http2 on;
    server_name kozy.ryndia.space;

    ssl_certificate /etc/letsencrypt/live/kozy.ryndia.space/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/kozy.ryndia.space/privkey.pem;
    include /etc/letsencrypt/options-ssl-nginx.conf;
    ssl_dhparam /etc/letsencrypt/ssl-dhparams.pem;

    # ── Security headers ───────────────────────────────────────────
    add_header X-Frame-Options "SAMEORIGIN" always;
    add_header X-Content-Type-Options "nosniff" always;
    add_header Referrer-Policy "strict-origin-when-cross-origin" always;
    add_header Strict-Transport-Security "max-age=31536000; includeSubDomains" always;

