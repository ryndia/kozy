cmd_dns() {
    # Emits a BIND zone file for the ryndia.space zone containing only kozy's
    # records, with the live DKIM key filled in — ready for Cloudflare's
    # "Import DNS records".
    local out="kozy-dns.txt"
    local mail_domain mail_hostname public_ip dkim_file dkim_value dkim_chunks dmarc_rua

    mail_domain="$(env_value MAIL_DOMAIN)";     mail_domain="${mail_domain:-$APP_DOMAIN}"
    mail_hostname="$(env_value MAIL_HOSTNAME)"; mail_hostname="${mail_hostname:-mail.$APP_DOMAIN}"
    dmarc_rua="$(env_value MAIL_POSTMASTER)";   dmarc_rua="${dmarc_rua:-postmaster@$mail_domain}"
    public_ip="$(curl -fsS --max-time 5 https://api.ipify.org 2>/dev/null || echo 'YOUR_VPS_IP')"

    dkim_file="/tmp/docker-mailserver/opendkim/keys/$mail_domain/mail.txt"
    # Every quoted chunk in mail.txt concatenated; the trailing ";" comment
    # carries no quotes, so it drops out on its own.
    dkim_value="$(compose exec -T mailserver cat "$dkim_file" 2>/dev/null \
        | tr -d '\r' | grep -o '"[^"]*"' | tr -d '"' | tr -d '\n')"

    if [ -z "$dkim_value" ]; then
        warn "No DKIM key found — run ./deploy.sh mail first"
        dkim_value="PASTE_DKIM_VALUE_FROM_deploy.sh_mail"
    fi

    # TXT strings cap at 255 chars; split exactly the way Cloudflare exports them.
    dkim_chunks="$(printf '%s' "$dkim_value" | fold -w 255 | sed 's/^/"/; s/$/"/' | tr '\n' ' ')"

    cat > "$out" <<DNS_EOF
;;
;; kozy.ryndia.space — records to import into the ryndia.space zone
;; Generated by deploy.sh on $(date -u '+%Y-%m-%d %H:%M UTC')
;;
;; Cloudflare → DNS → Import and Export → Import DNS records.
;; IMPORTANT: leave "Proxy imported DNS records" UNCHECKED, then switch the
;; orange cloud on for "kozy" only. $mail_hostname must stay DNS-only —
;; Cloudflare does not proxy SMTP, and a proxied mail host breaks delivery.
;;
;; No MX record: this mail server is send-only (OTP delivery).
;;

;; Web
$APP_DOMAIN.	1	IN	A	$public_ip

;; Mail host — MUST remain DNS only (grey cloud)
$mail_hostname.	1	IN	A	$public_ip

;; SPF — only this host may send as @$mail_domain
$mail_domain.	1	IN	TXT	"v=spf1 ip4:$public_ip -all"

;; DKIM — signs every outgoing OTP mail
mail._domainkey.$mail_domain.	1	IN	TXT	$dkim_chunks

;; DMARC — reports go to a mailbox that can actually receive them
_dmarc.$mail_domain.	1	IN	TXT	"v=DMARC1; p=none; rua=mailto:$dmarc_rua"
DNS_EOF

    ok "Wrote $out"
    echo ""
    cat "$out"
    echo ""
    warn "Also set the ryndia.space SSL/TLS mode to Full (strict) — $APP_DOMAIN is proxied."
    warn "Cross-domain DMARC reports need one record on the reporting domain:"
    warn "  TXT  $mail_domain._report._dmarc.<reporting-domain>  →  \"v=DMARC1\""
}

